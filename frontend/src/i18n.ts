export function t(key: string, values?: TranslationValues) {
  const template = appLocale === "ja" ? (ja[key] ?? key) : key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}
