use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const GENERATED_RELATIVE_PATH: &str = "frontend/src/api/generated/contract.ts";

fn main() {
    let check = match std::env::args().skip(1).collect::<Vec<_>>().as_slice() {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => {
            eprintln!("usage: generate-ipc-contract [--check]");
            std::process::exit(2);
        }
    };

    let output = render_contract();
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(GENERATED_RELATIVE_PATH);
    if check {
        match fs::read_to_string(&path) {
            Ok(current) if current == output => return,
            Ok(_) => eprintln!(
                "{GENERATED_RELATIVE_PATH} is stale; run `bun run ipc:generate` and commit the result"
            ),
            Err(error) => eprintln!("failed to read {}: {error}", path.display()),
        }
        std::process::exit(1);
    }

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create generated IPC contract directory");
    }
    fs::write(&path, output).expect("write generated IPC contract");
    println!("generated {GENERATED_RELATIVE_PATH}");
}

fn render_contract() -> String {
    let mut output = String::from(
        "// @generated by `bun run ipc:generate` from src/ipc/contract.rs.\n\
         // Do not edit this file directly.\n\n\
         import type {\n\
           AccountFeedSummary,\n\
           AccountListSummary,\n\
           AccountProfileSummary,\n\
           AccountRelationshipSummary,\n\
           AccountSummary,\n\
           AccountTimelinePageResponse,\n\
           AppSnapshot,\n\
           ComposeOutboxItem,\n\
           CustomEmojiSummary,\n\
           DbSummary,\n\
           HashtagSuggestion,\n\
           MediaAttachment,\n\
           MentionSuggestion,\n\
           NotificationMutedAccountSummary,\n\
           PollSummary,\n\
           PluginSnapshot,\n\
           SettingsSnapshot,\n\
           StatusIdentity,\n\
           StatusBarSnapshot,\n\
           StatusViewerStateSummary,\n\
           TimelineDisplayFilter,\n\
           TimelinePageResponse,\n\
           TimelineStatus,\n\
           WebSocketStatus,\n\
         } from \"../../types/app\";\n\n\
         import type { DiagnosticsSnapshot, SupportBundle } from \"../diagnostics\";\n\
         import type { FrontendHealthSnapshot } from \"../observability\";\n\n\
         export type IpcCommandKind = \"read\" | \"mutation\";\n\
         export type IpcCancelPolicy = \"unsupported\" | \"cooperative\";\n\n\
         export type IpcCommandDescriptor = {\n\
           kind: IpcCommandKind;\n\
           timeoutMs: number;\n\
           cancel: IpcCancelPolicy;\n\
           capability: string;\n\
           argsType: string;\n\
           resultType: string;\n\
         };\n\n\
         export const IPC_COMMANDS = {\n",
    );

    for command in contract::COMMANDS {
        writeln!(output, "  {}: {{", command.name).expect("write command name");
        writeln!(output, "    kind: \"{}\",", command.kind).expect("write kind");
        writeln!(output, "    timeoutMs: {},", command.timeout_ms).expect("write timeout");
        writeln!(output, "    cancel: \"{}\",", command.cancel).expect("write cancel");
        writeln!(output, "    capability: \"{}\",", command.capability).expect("write capability");
        writeln!(output, "    argsType: {:?},", command.args_type).expect("write args type");
        writeln!(output, "    resultType: {:?},", command.result_type).expect("write result type");
        output.push_str("  },\n");
    }

    output.push_str(
        "} as const satisfies Record<string, IpcCommandDescriptor>;\n\n\
         export type IpcCommandName = keyof typeof IPC_COMMANDS;\n\
         export type IpcCommandMetadata<C extends IpcCommandName> =\n\
           (typeof IPC_COMMANDS)[C];\n\
         export type IpcCommandArgsTypeName<C extends IpcCommandName> =\n\
           IpcCommandMetadata<C>[\"argsType\"];\n\
         export type IpcCommandResultTypeName<C extends IpcCommandName> =\n\
           IpcCommandMetadata<C>[\"resultType\"];\n\n\
         type CommandsOfKind<K extends IpcCommandKind> = {\n\
           [C in IpcCommandName]: IpcCommandMetadata<C>[\"kind\"] extends K ? C : never;\n\
         }[IpcCommandName];\n\n\
         export type RetryableReadCommand = CommandsOfKind<\"read\">;\n\
         export type MutationCommand = CommandsOfKind<\"mutation\">;\n\n",
    );

    output.push_str("\nexport const IPC_DTO_SCHEMAS = {\n");
    for dto in dto::DTOS {
        writeln!(output, "  {:?}: {{", dto.name).expect("write DTO name");
        output.push_str("    fields: [\n");
        for field in dto.fields {
            writeln!(
                output,
                "      {{ rustName: {:?}, serializedName: {:?}, type: {:?}, optional: {} }},",
                field.rust_name, field.serialized_name, field.ts_type, field.optional
            )
            .expect("write DTO field");
        }
        output.push_str("    ],\n  },\n");
    }
    output.push_str("} as const;\n\n");

    for dto in dto::DTOS {
        writeln!(output, "export type {} = {{", dto.name).expect("write DTO declaration");
        for field in dto.fields {
            writeln!(
                output,
                "  {}{}: {};",
                field.serialized_name,
                if field.optional { "?" } else { "" },
                field.ts_type
            )
            .expect("write DTO property");
        }
        output.push_str("};\n\n");
    }

    output.push_str("export type TypedIpcCommandArgs = {\n");
    for command in dto::TYPED_COMMANDS {
        writeln!(output, "  {:?}: {};", command.name, command.args_type)
            .expect("write typed command args");
    }
    output.push_str("};\n\nexport type TypedIpcCommandResult = {\n");
    for command in dto::TYPED_COMMANDS {
        writeln!(output, "  {:?}: {};", command.name, command.result_type)
            .expect("write typed command result");
    }
    output.push_str(
        "};\n\n\
         export type TypedIpcCommand = keyof TypedIpcCommandArgs;\n\n",
    );

    output.push_str("export type RawIpcCommandResult = {\n");
    for command in dto::RAW_COMMANDS {
        writeln!(output, "  {:?}: {};", command.name, command.result_type)
            .expect("write raw command result");
    }
    output.push_str("};\n\nexport type RawIpcCommand = keyof RawIpcCommandResult;\n\n");

    output.push_str(
        "/**\n\
          * Forward-compatible enum policy for values received from remote servers or DB rows:\n\
          * preserve the raw string, render an explicit fallback, and disable behavior that\n\
          * requires a known value. Never silently coerce an unknown value to a known variant.\n\
          */\n\
         export const IPC_UNKNOWN_ENUM_POLICY = {\n\
           preserveRawValue: true,\n\
           unknownBehavior: \"render-fallback-and-disable-unsupported-action\",\n\
         } as const;\n\n\
         declare const unknownEnumBrand: unique symbol;\n\
         export type UnknownEnumValue = string & { readonly [unknownEnumBrand]: true };\n\
         export type ForwardCompatibleEnum<Known extends string> =\n\
           | Known\n\
           | UnknownEnumValue;\n",
    );

    writeln!(
        output,
        "\nexport const SETTINGS_SCHEMA_VERSION = {} as const;",
        contract::SETTINGS_SCHEMA_VERSION
    )
    .expect("write settings schema version");
    output.push_str("\nexport const SETTING_DESCRIPTORS = {\n");
    for setting in contract::SETTINGS {
        writeln!(output, "  {:?}: {{", setting.key).expect("write setting key");
        writeln!(output, "    schemaVersion: {},", setting.schema_version)
            .expect("write setting schema version");
        writeln!(output, "    rustType: {:?},", setting.rust_type)
            .expect("write setting Rust type");
        writeln!(output, "    snapshotField: {:?},", setting.snapshot_field)
            .expect("write setting snapshot field");
        output.push_str("  },\n");
    }
    output.push_str(
        "} as const;\n\n\
         export type SettingKey = keyof typeof SETTING_DESCRIPTORS;\n\
         export const SETTING_KEYS = Object.keys(SETTING_DESCRIPTORS) as SettingKey[];\n\
         export const SETTING_SNAPSHOT_FIELD_BY_KEY = Object.fromEntries(\n\
           SETTING_KEYS.map((key) => [key, SETTING_DESCRIPTORS[key].snapshotField]),\n\
         ) as { [K in SettingKey]: (typeof SETTING_DESCRIPTORS)[K][\"snapshotField\"] };\n",
    );
    output
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_contract_exposes_the_policy_and_all_commands() {
        let output = render_contract();
        assert!(output.contains("IPC_UNKNOWN_ENUM_POLICY"));
        for command in contract::COMMANDS {
            assert!(output.contains(&format!("  {}: {{", command.name)));
        }
        for command in dto::TYPED_COMMANDS {
            assert!(contract::COMMANDS
                .iter()
                .any(|entry| entry.name == command.name));
            assert!(output.contains(&format!("  {:?}: ", command.name)));
        }
        for command in contract::COMMANDS {
            assert!(
                dto::TYPED_COMMANDS
                    .iter()
                    .any(|typed| typed.name == command.name)
                    || dto::RAW_COMMANDS.iter().any(|raw| raw.name == command.name),
                "command {} is missing from the typed registry",
                command.name
            );
        }
        for dto in dto::DTOS {
            assert!(output.contains(&format!("export type {} = {{", dto.name)));
        }
    }
}
